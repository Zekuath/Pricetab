#!/usr/bin/env node
/* Builds `src/sanctions.js` from the OFAC sanctioned-address lists.
 *
 * The lists are the US Treasury's own, published as part of the SDN file and
 * republished per chain as static JSON by
 * `github.com/0xB10C/ofac-sanctioned-digital-currency-addresses` (branch
 * `lists`), which rebuilds them every week or two straight from the source.
 *
 *     node scripts/build-sanctions.js          # rewrite src/sanctions.js
 *     node scripts/build-sanctions.js --check  # fail if it is out of date
 *
 * **Why this is a build step and not a fetch.** Checking an address against a
 * list is a question about an address, and the whole point of answering it
 * here is that the address never leaves the machine. Downloading the list at
 * runtime would keep that property but cost a request, a new remote host and a
 * dependency on a repository staying where it is; bundling it costs ~30 KB and
 * keeps the extension's "zero permissions, nothing leaves the device" promise
 * exactly as it was. The trade is staleness between releases, which for a
 * sanctions list — amended a handful of times a year — is the right way round.
 *
 * Only the chains PriceTab can actually watch are kept (`WATCH_CHAINS` plus
 * ERC-20): Bitcoin, Ethereum and its token space, Litecoin, Bitcoin Cash and
 * Zcash. There is no Dogecoin list upstream. Every EVM list is folded into one
 * set because they share an address space — an address listed on Arbitrum is
 * the same string as on Ethereum, and a set is not a claim about which chain.
 */
const fs = require("fs");
const path = require("path");

const BASE =
  "https://raw.githubusercontent.com/0xB10C/" +
  "ofac-sanctioned-digital-currency-addresses/lists/sanctioned_addresses_";
const OUT = path.join(__dirname, "..", "src", "sanctions.js");

// EVM lists share one address space; the rest are their own chains
const EVM = ["ETH", "USDT", "USDC", "ARB", "BSC", "ETC"];
const CHAINS = { BTC: "XBT", LTC: "LTC", BCH: "BCH", ZEC: "ZEC" };

const get = async (name) => {
  const res = await fetch(BASE + name + ".json");
  if (res.status === 404) return [];
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const rows = await res.json();
  if (!Array.isArray(rows)) throw new Error(`${name}: not an array`);
  return rows.filter((a) => typeof a === "string" && a.trim());
};

// The same normalisation `normalizeWatchAddress` does, so a list entry and a
// pasted address are compared in the same shape
const clean = (a) => a.trim().replace(/^bitcoincash:/i, "");

const build = async () => {
  const evm = new Set();
  for (const name of EVM) {
    for (const a of await get(name)) {
      if (/^0x[0-9a-fA-F]{40}$/.test(a.trim())) evm.add(a.trim().toLowerCase());
    }
  }
  const chains = {};
  for (const [coin, name] of Object.entries(CHAINS)) {
    chains[coin] = [...new Set((await get(name)).map(clean))].sort();
  }
  const stamp = new Date().toISOString().slice(0, 10);
  const block = (rows) => JSON.stringify(rows.join("\n"));
  const total = evm.size + Object.values(chains).reduce((n, r) => n + r.length, 0);

  return `/* SANCTIONED ADDRESSES, CHECKED ON THIS DEVICE.
 *
 * **Generated by \`scripts/build-sanctions.js\`. Do not edit by hand.**
 *
 * The US Treasury's OFAC list of sanctioned digital-currency addresses, for
 * the chains this extension can watch. ${total} addresses, bundled as of
 * ${stamp}.
 *
 * **It is bundled rather than fetched, and that is the feature.** The question
 * "is this address on a list" is a question *about an address*, and asking a
 * server it would send the address there — which is the one thing this
 * extension promises it does not do. A list that ships with the release is
 * compared in memory: nothing is requested, no host is added, and the address
 * never leaves the machine.
 *
 * **What it is not.** This is a sanctions list, not a fraud database: it says
 * an address was designated by a government, and says nothing at all about the
 * addresses that are not on it. The wording on screen has to match that — see
 * \`ref/portfolio.md\`. Scam-reporting lists are a different question with a
 * different shape (they change daily, so they cannot be bundled honestly).
 *
 * The strings are split on first use rather than written as arrays: a ${total}-
 * element array literal is ${total} tokens for a parser that runs on every new
 * tab, and a string is one.
 */
const SANCTIONS_LIST_DATE = ${JSON.stringify(stamp)};

const SANCTIONS_EVM = ${block([...evm].sort())};

const SANCTIONS_BY_CHAIN = {
${Object.entries(chains)
  .map(([coin, rows]) => `  ${coin}: ${block(rows)},`)
  .join("\n")}
};

let _sanctionSets = null;

/* Is this address on the bundled OFAC list?
 *
 * Case matters on the UTXO chains and does not on EVM, so the two are held
 * apart rather than lower-cased together — a Bitcoin address differing only in
 * case is a different address, and folding them would invent matches.
 */
const isSanctionedAddress = (address) => {
  const value = normalizeWatchAddress(address);
  if (!value) return false;
  if (!_sanctionSets) {
    _sanctionSets = {
      evm: new Set(SANCTIONS_EVM ? SANCTIONS_EVM.split("\\n") : []),
      other: new Set(),
    };
    for (const rows of Object.values(SANCTIONS_BY_CHAIN)) {
      for (const a of rows ? rows.split("\\n") : []) _sanctionSets.other.add(a);
    }
  }
  if (/^0x/i.test(value)) return _sanctionSets.evm.has(value.toLowerCase());
  return _sanctionSets.other.has(value);
};
`;
};

(async () => {
  const text = await build();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    // The date stamp moves on every run, so compare the address blocks only
    const bodies = (s) => s.replace(/^const SANCTIONS_LIST_DATE = .*$/m, "");
    if (bodies(current) !== bodies(text)) {
      console.error("✖ src/sanctions.js is out of date — run this without --check");
      process.exit(1);
    }
    console.log("✔ src/sanctions.js matches the published lists");
    return;
  }
  fs.writeFileSync(OUT, text);
  const n = (text.match(/\n/g) || []).length;
  console.log(`✔ wrote src/sanctions.js (${n} lines, ${Math.round(text.length / 1024)} KB)`);
})();
